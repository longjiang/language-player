-- SPEC-102: affiliates, coupon codes, and the payment/commission ledger.
--
-- These are server-only tables: Flask uses the trusted backend role and there
-- are no authenticated/anon grants. RLS is enabled as a default-deny guard so
-- a future accidental grant does not expose them.

begin;

-- ── Affiliates ──────────────────────────────────────────────────────────

create table public.affiliates (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  code text not null,
  commission_bps integer not null default 1500
    check (commission_bps between 0 and 10000),
  active boolean not null default true,
  paypal_email text,
  onboarded_at timestamptz,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index affiliates_code_lower_key on public.affiliates (lower(code));
create index affiliates_active_idx on public.affiliates (active);

create table public.user_affiliate_attributions (
  user_id uuid primary key references auth.users(id) on delete cascade,
  affiliate_id bigint not null references public.affiliates(id) on delete cascade,
  attributed_at timestamptz not null default now(),
  expires_at timestamptz not null,
  first_affiliate_id bigint references public.affiliates(id) on delete set null,
  first_attributed_at timestamptz,
  first_expires_at timestamptz,
  source text not null default 'cookie'
    check (source in ('cookie', 'signup', 'manual')),
  updated_at timestamptz not null default now()
);
create index user_affiliate_attributions_affiliate_idx
  on public.user_affiliate_attributions (affiliate_id);

-- ── Coupons ─────────────────────────────────────────────────────────────

create table public.coupons (
  id bigint generated by default as identity primary key,
  code text not null,
  internal_name text not null,
  discount_type text not null check (discount_type in ('percent', 'amount')),
  percent_off numeric(5,2),
  amount_off_cents integer,
  currency text not null default 'usd',
  applies_to text not null default 'lifetime'
    check (applies_to in ('lifetime', 'monthly', 'annual', 'all')),
  duration text not null default 'once' check (duration in ('once', 'forever')),
  max_redemptions integer not null default 10000
    check (max_redemptions between 1 and 10000),
  expires_at timestamptz,
  active boolean not null default true,
  stripe_coupon_id_live text,
  stripe_coupon_id_test text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (discount_type = 'percent' and percent_off is not null and amount_off_cents is null)
    or (discount_type = 'amount' and amount_off_cents is not null and percent_off is null)
  )
);
create unique index coupons_code_lower_key on public.coupons (lower(code));
create index coupons_active_idx on public.coupons (active, expires_at);

-- ── Statements and ledger ───────────────────────────────────────────────

create table public.affiliate_statements (
  id bigint generated by default as identity primary key,
  affiliate_id bigint not null references public.affiliates(id) on delete restrict,
  period_start date not null,
  period_end date not null,
  statement_number text not null unique,
  status text not null default 'pending' check (status in ('pending', 'paid', 'void')),
  currency text not null default 'usd',
  total_commission_cents integer not null,
  paypal_email text,
  paid_at timestamptz,
  paid_by uuid references auth.users(id),
  payment_reference text,
  notes text,
  created_at timestamptz not null default now(),
  unique (affiliate_id, period_start, period_end)
);
create index affiliate_statements_affiliate_idx
  on public.affiliate_statements (affiliate_id, period_start desc);

create table public.payment_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subscription_id bigint references public.user_subscriptions(id) on delete set null,
  processor text not null
    check (processor in ('stripe', 'paypal', 'app-store', 'play', 'manual')),
  processor_event_id text not null,
  kind text not null check (kind in ('payment', 'refund', 'chargeback', 'adjustment')),
  amount_cents integer not null,
  tax_cents integer not null default 0,
  discount_cents integer not null default 0,
  commission_base_cents integer not null,
  currency text not null default 'usd',
  coupon_id bigint references public.coupons(id) on delete set null,
  affiliate_id bigint references public.affiliates(id) on delete set null,
  occurred_at timestamptz not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (processor, processor_event_id, kind)
);
create index payment_events_user_idx on public.payment_events (user_id, occurred_at desc);
create index payment_events_affiliate_idx on public.payment_events (affiliate_id, occurred_at desc);

create table public.affiliate_commissions (
  id bigint generated by default as identity primary key,
  payment_event_id bigint not null unique
    references public.payment_events(id) on delete cascade,
  affiliate_id bigint not null references public.affiliates(id) on delete restrict,
  user_id uuid not null references auth.users(id) on delete cascade,
  subscription_id bigint references public.user_subscriptions(id) on delete set null,
  rate_bps integer not null,
  base_cents integer not null,
  commission_cents integer not null,
  currency text not null default 'usd',
  status text not null default 'pending'
    check (status in ('pending', 'paid', 'reversed')),
  statement_id bigint references public.affiliate_statements(id) on delete set null,
  reversal_of_commission_id bigint references public.affiliate_commissions(id),
  created_at timestamptz not null default now()
);
create index affiliate_commissions_affiliate_idx
  on public.affiliate_commissions (affiliate_id, created_at desc);
create index affiliate_commissions_statement_idx
  on public.affiliate_commissions (statement_id);

create table public.coupon_redemptions (
  id bigint generated by default as identity primary key,
  coupon_id bigint not null references public.coupons(id) on delete restrict,
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'reserved'
    check (status in ('reserved', 'confirmed', 'released')),
  reserved_until timestamptz,
  payment_event_id bigint references public.payment_events(id) on delete set null,
  discount_cents integer not null default 0,
  currency text not null default 'usd',
  created_at timestamptz not null default now(),
  confirmed_at timestamptz,
  unique (coupon_id, user_id)
);
create index coupon_redemptions_active_idx
  on public.coupon_redemptions (coupon_id, status);

-- ── Affiliate attribution on the subscription row ───────────────────────

alter table public.user_subscriptions
  add column if not exists affiliate_id bigint
    references public.affiliates(id) on delete set null,
  add column if not exists affiliate_attributed_at timestamptz;

-- ── Default-deny RLS ────────────────────────────────────────────────────

alter table public.affiliates enable row level security;
alter table public.user_affiliate_attributions enable row level security;
alter table public.coupons enable row level security;
alter table public.affiliate_statements enable row level security;
alter table public.payment_events enable row level security;
alter table public.affiliate_commissions enable row level security;
alter table public.coupon_redemptions enable row level security;

commit;
